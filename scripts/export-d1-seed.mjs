/**
 * Exports the seeded catalog as SQLite SQL for Cloudflare D1.
 *
 * A throwaway database is seeded first, so only seed data is exported and no
 * local QA edits leak into production.
 *
 * Run: node scripts/export-d1-seed.mjs
 * Then: npx wrangler d1 execute kingdom-custom-print --remote --file=db/seed.sql
 */
import { DatabaseSync } from "node:sqlite";
import { rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

const file = ".local-db/export.sqlite";
rmSync(file, { force: true });
const seeded = spawnSync(process.execPath, ["scripts/seed-sqlite.mjs", "--force"], {
  stdio: "inherit",
  env: { ...process.env, LOCAL_DB_PATH: file },
});
if (seeded.status !== 0) process.exit(seeded.status ?? 1);

const db = new DatabaseSync(file);
const quote = (value) => {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "bigint") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
};

const lines = [
  "-- Kingdom Custom Print catalog seed (generated by scripts/export-d1-seed.mjs)",
  "-- Safe to re-run: catalog tables are replaced, settings are upserted.",
  "-- D1 imports run as one atomic batch, so no BEGIN/COMMIT is needed.",
  "DELETE FROM product_images;",
  "DELETE FROM price_breaks;",
  "DELETE FROM product_sizes;",
  "DELETE FROM product_colors;",
  "DELETE FROM products;",
  "DELETE FROM categories;",
  "DELETE FROM site_settings;",
];

const insertRows = (table, columns, rows) => {
  if (!rows.length) return;
  for (const row of rows) {
    lines.push(
      `INSERT INTO ${table} (${columns.join(", ")}) VALUES (${columns.map((column) => quote(row[column])).join(", ")});`
    );
  }
};

insertRows(
  "categories",
  ["id", "slug", "name", "description", "sort_order"],
  db.prepare("SELECT id, slug, name, description, sort_order FROM categories ORDER BY id").all()
);
insertRows(
  "products",
  ["id", "slug", "name", "style_code", "category_id", "kind", "sale_mode", "blurb", "description",
    "material", "base_price", "compare_at", "print_fee_per_side", "print_area", "featured", "active", "sort_order"],
  db.prepare(`SELECT id, slug, name, style_code, category_id, kind, sale_mode, blurb, description,
      material, base_price, compare_at, print_fee_per_side, print_area, featured, active, sort_order
    FROM products ORDER BY id`).all()
);
insertRows(
  "product_colors",
  ["id", "product_id", "slug", "name", "hex", "sort_order", "front_image", "back_image"],
  db.prepare("SELECT id, product_id, slug, name, hex, sort_order, front_image, back_image FROM product_colors ORDER BY id").all()
);
insertRows(
  "product_sizes",
  ["id", "product_id", "label", "surcharge", "sort_order"],
  db.prepare("SELECT id, product_id, label, surcharge, sort_order FROM product_sizes ORDER BY id").all()
);
insertRows(
  "price_breaks",
  ["id", "product_id", "min_qty", "amount_off"],
  db.prepare("SELECT id, product_id, min_qty, amount_off FROM price_breaks ORDER BY id").all()
);
insertRows(
  "product_images",
  ["id", "product_id", "url", "alt", "sort_order"],
  db.prepare("SELECT id, product_id, url, alt, sort_order FROM product_images ORDER BY id").all()
);
insertRows(
  "site_settings",
  ["key", "value", "updated_at"],
  db.prepare("SELECT key, value, updated_at FROM site_settings ORDER BY key").all()
);

lines.push("");

writeFileSync("db/seed.sql", lines.join("\n"));
console.log(`Wrote db/seed.sql (${lines.length} statements)`);
db.close();
rmSync(file, { force: true });
