/** Browser checks with mocked draft and upload endpoints; no storefront data is changed. */
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { chromium, webkit } from "playwright";
import { defaultHomepageLayout, homepageContentFromSettings } from "../lib/homepage-builder.ts";

const base = process.env.QA_BASE ?? "http://localhost:3025";
const password = process.env.QA_EDITOR_PASSWORD;
if (!password) throw new Error("Set QA_EDITOR_PASSWORD for an isolated development server.");
const imagePath = new URL("../public/img/category-prints/shirts.webp", import.meta.url);
const imageBytes = await readFile(imagePath);
const uploadUrl = "/api/product-media/11111111-1111-4111-8111-111111111111";
const engines = [["Chrome", chromium, { channel: "chrome" }], ["Edge", chromium, { channel: "msedge" }], ["WebKit", webkit, {}]].filter(([name]) => !process.env.QA_ENGINE || process.env.QA_ENGINE === name);

for (const [index, [name, engine, options]] of engines.entries()) {
  const browser = await engine.launch({ ...options, headless: true });
  const context = await browser.newContext({ viewport: { width: 375, height: 900 }, hasTouch: true, extraHTTPHeaders: { "x-forwarded-for": `198.51.100.${index + 31}` } });
  const page = await context.newPage();
  const pageErrors = [];
  page.on("pageerror", error => pageErrors.push(error.message));
  try {
    await page.goto(`${base}/admin`, { waitUntil: "domcontentloaded", timeout: 60000 });
    await page.locator('button[type="submit"]:enabled').waitFor({ timeout: 30000 });
    await page.locator('input[type="password"]').fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await page.getByRole("heading", { name: "Store overview" }).waitFor({ timeout: 60000 });
    const settingsResponse = await context.request.get(`${base}/api/admin/settings`);
    assert.equal(settingsResponse.ok(), true, "settings load");
    const content = homepageContentFromSettings(await settingsResponse.json());
    let draft = { ...defaultHomepageLayout(), content, baseContent: content };
    let published = draft, previous = null, revision = null;
    await page.route("**/api/admin/homepage-draft", async route => {
      const request = route.request();
      if (request.method() === "PUT") { const { expectedRevision, ...next } = request.postDataJSON(); if (expectedRevision !== revision) { await route.fulfill({ status: 409, json: { error: "The saved draft changed in another session. Copy any unsaved edits, then reload the editor." } }); return; } draft = next; revision = crypto.randomUUID(); await route.fulfill({ json: { ok: true, revision } }); }
      else if (request.method() === "POST") {
        const { action, expectedRevision } = request.postDataJSON();
        if (expectedRevision !== revision) { await route.fulfill({ status: 409, json: { error: "The saved draft changed in another session. Copy any unsaved edits, then reload the editor." } }); return; }
        if (action === "publish") { previous = published; published = { ...draft, baseContent: draft.content }; draft = published; }
        else { const old = published; published = previous; previous = old; draft = published; }
        revision = crypto.randomUUID(); await route.fulfill({ json: { ok: true, layout: published, revision, hasPrevious: Boolean(previous) } });
      } else if (request.method() === "DELETE") { draft = null; revision = null; await route.fulfill({ json: { ok: true } }); }
      else await route.fulfill({ json: { layout: draft ?? published, revision, hasDraft: Boolean(draft), hasPrevious: Boolean(previous) } });
    });
    await page.route("**/api/admin/product-media", route => route.fulfill({ json: { url: uploadUrl } }));
    await page.route(`**${uploadUrl}`, route => route.fulfill({ body: imageBytes, contentType: "image/webp" }));
    await page.locator(".admin-menu-toggle").click();
    await page.locator("#admin-menu").getByRole("button", { name: "Homepage sections" }).click();
    await page.waitForURL("**/admin?tab=homepage");
    await page.getByRole("heading", { name: "Homepage editor" }).waitFor();
    let frame = page.frameLocator('iframe[title="mobile homepage draft preview"]');
    await frame.locator('.kcp-home:visible [data-home-field="heroHeadlineTop"]').waitFor({ timeout: 60000 });
    await frame.locator('.kcp-home:visible').evaluate(root => { const hidden = document.createElement('div'); hidden.hidden = true; hidden.dataset.qaHiddenCopy = 'true'; hidden.append(root.cloneNode(true)); root.before(hidden); });
    await page.getByLabel("Hero headline, first line").fill("Fresh ideas");
    await frame.locator('.kcp-home:visible [data-home-field="heroHeadlineTop"]').getByText("Fresh ideas").waitFor();
    await frame.locator('[data-qa-hidden-copy]').evaluateAll(elements => elements.forEach(element => element.remove()));
    await frame.locator('.kcp-home').evaluateAll(roots => roots.forEach(root => { if (!root.getClientRects().length) root.remove(); }));
    await frame.locator('.kcp-home:visible').evaluate(root => { const replacement = root.cloneNode(true); replacement.dataset.qaReplacement = 'true'; replacement.querySelector('[data-home-field="heroHeadlineTop"]').textContent = 'Outdated'; root.hidden = true; root.after(replacement); });
    await frame.locator('[data-qa-replacement] [data-home-field="heroHeadlineTop"]').getByText("Fresh ideas").waitFor();
    await frame.locator('[data-qa-replacement]').evaluate(element => { element.previousElementSibling.hidden = false; element.remove(); });
    await frame.locator('[data-qa-hidden-copy], [data-qa-replacement]').evaluateAll(elements => elements.forEach(element => element.remove()));
    await frame.locator('.kcp-home').evaluateAll(roots => roots.forEach(root => { if (!root.getClientRects().length) root.remove(); }));
    await frame.locator('.kcp-home:visible [data-home-field="heroHeadlineTop"]').dblclick();
    await page.waitForFunction(() => Array.from(document.querySelectorAll('button')).some(button => button.textContent === 'Save draft' && button.disabled));
    await frame.locator('[data-home-field="heroHeadlineTop"][contenteditable="true"]').fill("Ideas in motion");
    await frame.locator('[data-home-field="heroHeadlineTop"]').press("Enter");
    await page.getByLabel("Hero headline, first line").waitFor();
    await page.waitForFunction(() => document.querySelector('#homepage-heroHeadlineTop')?.value === 'Ideas in motion');
    await page.getByRole("button", { name: "Move Hero buttons up" }).click();
    await page.waitForFunction(() => document.querySelector('iframe[title="mobile homepage draft preview"]')?.contentDocument?.querySelector('.kcp-home > [data-home-section]')?.getAttribute('data-home-section') === 'hero-actions');
    if (name === "Chrome") {
      const source = page.locator('[data-section-id="hero-actions"] .admin-section-handle');
      const target = page.locator('[data-section-id="hero"]');
      await source.scrollIntoViewIfNeeded();
      const from = await source.boundingBox(), to = await target.boundingBox();
      assert.ok(from && to);
      const cdp = await context.newCDPSession(page);
      await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: from.x + from.width / 2, y: from.y + from.height / 2 }] });
      await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: to.x + to.width / 2, y: to.y + to.height / 2 }] });
      await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
      await page.waitForFunction(() => document.querySelector('.admin-section-list > li')?.getAttribute('data-section-id') === 'hero');
      await page.getByRole("button", { name: "Move Hero buttons up" }).click();
      const orderBeforeAutoScroll = await page.locator(".admin-section-list > li").evaluateAll(items => items.map(item => item.getAttribute("data-section-id")));
      const autoScrollHandle = page.locator('[data-section-id="ready-to-ship"] .admin-section-handle');
      await autoScrollHandle.evaluate(element => element.scrollIntoView({ block: "center" }));
      const autoScrollBox = await autoScrollHandle.boundingBox();
      assert.ok(autoScrollBox);
      const scrollBefore = await page.evaluate(() => scrollY);
      await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: autoScrollBox.x + autoScrollBox.width / 2, y: autoScrollBox.y + autoScrollBox.height / 2 }] });
      await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: autoScrollBox.x + autoScrollBox.width / 2, y: 890 }] });
      await page.waitForTimeout(700);
      assert.ok(await page.evaluate(() => scrollY) > scrollBefore + 20, "touch drag auto-scrolls near the viewport edge");
      await cdp.send("Input.dispatchTouchEvent", { type: "touchCancel", touchPoints: [] });
      await page.waitForTimeout(200);
      assert.deepEqual(await page.locator(".admin-section-list > li").evaluateAll(items => items.map(item => item.getAttribute("data-section-id"))), orderBeforeAutoScroll, "cancelled touch drag leaves the order unchanged");
      await cdp.detach();
    }
    await page.getByRole("button", { name: "Hero buttons", exact: true }).click();
    await page.getByLabel("First button text").fill("Browse the shop");
    await page.getByLabel("First button link").fill("/shop?kind=tee");
    await frame.locator('[data-home-hero-link="primary"][href="/shop?kind=tee"]').waitFor();
    await frame.locator('[data-home-hero-action="primaryText"]').getByText("Browse the shop").waitFor();
    await frame.locator('[data-home-hero-action="primaryText"]').evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
    await frame.locator('[data-home-hero-action="primaryText"]').dblclick();
    await frame.locator('[data-home-hero-action="primaryText"][contenteditable="true"]').fill("Shop the collection");
    await frame.locator('[data-home-hero-action="primaryText"]').press("Enter");
    await page.waitForFunction(() => document.querySelector('#hero-action-primaryText')?.value === 'Shop the collection');
    await page.getByRole("button", { name: "Questions", exact: true }).click();
    await page.getByLabel("Question 1", { exact: true }).fill("Can you help me with my design?");
    await page.getByLabel("Answer 1", { exact: true }).fill("Yes, contact our team.");
    await frame.locator('[data-home-questions-list] summary').first().getByText("Can you help me with my design?").waitFor();
    const previewContactLink = frame.locator('[data-home-questions-list] a[href="/contact"]');
    await previewContactLink.waitFor({ state: "attached" });
    assert.equal((await previewContactLink.textContent())?.trim(), "Get in touch");
    await page.getByRole("button", { name: "Hide Ready to ship" }).click();
    await page.waitForFunction(() => document.querySelector('iframe[title="mobile homepage draft preview"]')?.contentDocument?.querySelector('[data-home-section="ready-to-ship"]')?.hasAttribute('hidden'));
    await page.getByRole("button", { name: "Show Ready to ship" }).click();
    await page.waitForFunction(() => !document.querySelector('iframe[title="mobile homepage draft preview"]')?.contentDocument?.querySelector('[data-home-section="ready-to-ship"]')?.hasAttribute('hidden'));
    await page.getByRole("button", { name: "Design banner", exact: true }).click();
    await page.getByLabel("Heading", { exact: true }).fill("Make your next design");
    await page.getByLabel("Button link").fill("/shop");
    await frame.locator('[data-home-banner="heading"]').getByText("Make your next design").waitFor();
    await frame.locator('[data-home-banner-link][href="/shop"]').waitFor();
    await frame.locator('[data-home-banner="heading"]').evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
    await frame.locator('[data-home-banner="heading"]').dblclick();
    await frame.locator('[data-home-banner="heading"][contenteditable="true"]').fill("Create your look");
    await frame.locator('[data-home-banner="heading"]').press("Enter");
    await page.waitForFunction(() => document.querySelector('#banner-heading')?.value === 'Create your look');
    await page.getByRole("button", { name: "Add message section" }).click();
    await page.getByLabel("Heading", { exact: true }).fill("Talk to our team");
    await page.getByLabel("Description", { exact: true }).fill("We can help with your order.");
    await page.getByLabel("Button text", { exact: true }).fill("Contact us");
    await page.getByLabel("Button link", { exact: true }).fill("/contact");
    await page.getByLabel("Background", { exact: true }).selectOption("dark");
    await page.getByLabel("Text alignment", { exact: true }).selectOption("center");
    await page.getByLabel("Image position", { exact: true }).selectOption("left");
    await frame.locator('.kcp-custom-message[data-tone="dark"][data-alignment="center"][data-image-position="left"]').waitFor();
    await page.getByLabel("Section image").setInputFiles({ name: "test.webp", mimeType: "image/webp", buffer: imageBytes });
    await page.getByLabel("Image description").fill("A sample shirt");
    await page.waitForFunction(url => document.querySelector('iframe[title="mobile homepage draft preview"]')?.contentDocument?.querySelector('.kcp-custom-message img')?.getAttribute('src') === url, uploadUrl);
    assert.equal(await frame.locator('.kcp-custom-message img').evaluate(image => getComputedStyle(image).order), "-1");
    await frame.locator(".kcp-custom-message h2").getByText("Talk to our team").waitFor();
    await frame.locator('.kcp-custom-message a[href="/contact"]').waitFor();
    await frame.locator(".kcp-custom-message h2").evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
    await frame.locator(".kcp-custom-message h2").dblclick();
    await frame.locator('.kcp-custom-message h2[contenteditable="true"]').fill("Speak with our team");
    await frame.locator(".kcp-custom-message h2").press("Enter");
    await page.waitForFunction(() => document.querySelector('#message-heading')?.value === 'Speak with our team');
    await page.getByRole("button", { name: "Move Speak with our team up" }).click();
    await page.getByRole("button", { name: "Hide Speak with our team" }).click();
    await page.waitForFunction(() => document.querySelector('iframe[title="mobile homepage draft preview"]')?.contentDocument?.querySelector('.kcp-custom-message')?.hasAttribute('hidden'));
    await page.getByRole("button", { name: "Show Speak with our team" }).click();
    await page.getByRole("button", { name: "Hero", exact: true }).click();
    await frame.locator(".kcp-custom-message h2").evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
    await frame.locator(".kcp-custom-message h2").click();
    await page.getByRole("button", { name: "Speak with our team", exact: true, pressed: true }).waitFor();
    await page.getByRole("button", { name: "Add questions section" }).click();
    await page.getByLabel("Heading", { exact: true }).fill("Common questions");
    await page.getByLabel("Question 1").fill("Can I get help with a design?");
    await page.getByLabel("Answer 1").fill("Please contact our team.");
    await frame.locator(".kcp-custom-faq h2").getByText("Common questions").waitFor();
    await frame.locator(".kcp-custom-faq summary").getByText("Can I get help with a design?").waitFor();
    await frame.locator(".kcp-custom-faq h2").evaluate(element => element.scrollIntoView({ block: "center", behavior: "instant" }));
    await frame.locator(".kcp-custom-faq h2").dblclick();
    await frame.locator('.kcp-custom-faq h2[contenteditable="true"]').fill("Frequently asked questions");
    await frame.locator(".kcp-custom-faq h2").press("Enter");
    await page.waitForFunction(() => document.querySelector('#faq-heading')?.value === 'Frequently asked questions');
    await page.setViewportSize({ width: 320, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, "questions editor fits at 320px");
    await page.setViewportSize({ width: 375, height: 900 });
    await page.getByRole("button", { name: "Add products section" }).click();
    await page.getByLabel("Heading", { exact: true }).fill("Selected products");
    const firstProduct = page.locator(".admin-product-picks label").first();
    const firstName = (await firstProduct.locator("span").innerText()).trim();
    await firstProduct.locator('input[type="checkbox"]').check();
    await frame.locator(".kcp-custom-products article").first().getByText(firstName, { exact: true }).waitFor();
    await page.getByRole("button", { name: "Hero", exact: true }).click();
    await page.getByRole("group", { name: "Edit Hero" }).waitFor();
    await page.getByLabel("Upload Hero image 1").setInputFiles({ name: "test.webp", mimeType: "image/webp", buffer: imageBytes });
    await page.waitForFunction(url => document.querySelector('iframe[title="mobile homepage draft preview"]')?.contentDocument?.querySelector('[data-home-hero-slide="1"] img')?.getAttribute('src') === url, uploadUrl);
    assert.equal(await page.getByRole("button", { name: "Publish", exact: true }).isDisabled(), true, "unsaved changes cannot publish");
    await page.getByRole("button", { name: "Save draft" }).click();
    await page.getByText("Draft saved.").waitFor();
    assert.equal(draft.content.heroHeadlineTop, "Ideas in motion");
    assert.equal(draft.content.heroImage1, uploadUrl);
    assert.equal(draft.designBanner.heading, "Create your look");
    assert.equal(draft.designBanner.buttonLink, "/shop");
    assert.equal(draft.heroActions.primaryText, "Shop the collection");
    assert.equal(draft.heroActions.primaryLink, "/shop?kind=tee");
    assert.equal(draft.questionsContent.items[0].answer, "Yes, contact our team.");
    assert.equal(draft.customBlocks[0].heading, "Speak with our team");
    assert.equal(draft.customBlocks[0].image, uploadUrl);
    assert.deepEqual(draft.customBlocks[0].style, { tone: "dark", alignment: "center", imagePosition: "left" });
    assert.equal(draft.customBlocks[1].faqItems[0].answer, "Please contact our team.");
    assert.equal(draft.customBlocks[2].productIds.length, 1);
    await page.getByRole("button", { name: "Publish", exact: true }).click();
    await page.getByText("Homepage published.").waitFor();
    assert.equal(published.sections[0], "hero-actions");
    page.once("dialog", dialog => dialog.accept());
    await page.getByRole("button", { name: "Restore previous" }).click();
    await page.getByText("Previous homepage restored.").waitFor();
    assert.equal(published.sections[0], "hero");
    for (const [label, width] of [["Mobile", 375], ["Tablet", 768], ["Desktop", 1280]]) {
      await page.getByRole("button", { name: label, exact: true }).click();
      frame = page.frameLocator(`iframe[title="${label.toLowerCase()} homepage draft preview"]`);
      await frame.locator('.kcp-home:visible [data-home-section="hero"]').waitFor({ timeout: 60000 });
      const dimensions = await page.locator(`iframe[title="${label.toLowerCase()} homepage draft preview"]`).evaluate(element => ({ viewport: element.clientWidth, visible: element.getBoundingClientRect().width, container: element.closest('.admin-preview-fit').clientWidth }));
      assert.equal(dimensions.viewport, width, `${label} preview viewport`);
      assert.ok(dimensions.visible <= dimensions.container + 1, `${label} preview fits its container`);
    }
    for (const width of [320, 375, 768, 1280]) {
      await page.setViewportSize({ width, height: 900 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `${width}px admin overflow`);
    }
    await page.getByRole("button", { name: "Website preview", exact: true }).click();
    await page.waitForURL("**/admin?tab=preview");
    await page.getByRole("heading", { name: "Website preview" }).waitFor();
    for (const [label, width] of [["Mobile", 375], ["Tablet", 768], ["Desktop", 1280]]) {
      await page.getByRole("button", { name: label, exact: true }).click();
      const title = `${label.toLowerCase()} storefront preview`;
      const storefront = page.locator(`iframe[title="${title}"]`);
      await storefront.waitFor();
      await page.frameLocator(`iframe[title="${title}"]`).locator("#home-title").waitFor({ timeout: 60000 });
      const dimensions = await storefront.evaluate(element => ({ viewport: element.clientWidth, visible: element.getBoundingClientRect().width, container: element.closest(".admin-preview-fit").clientWidth }));
      assert.equal(dimensions.viewport, width, `${label} storefront preview viewport`);
      assert.ok(dimensions.visible <= dimensions.container + 1, `${label} storefront preview fits its container`);
    }
    await page.setViewportSize({ width: 320, height: 900 });
    await page.getByRole("button", { name: "Mobile", exact: true }).click();
    const mobileStorefront = page.locator('iframe[title="mobile storefront preview"]');
    await mobileStorefront.waitFor();
    await page.frameLocator('iframe[title="mobile storefront preview"]').locator("#home-title").waitFor({ timeout: 60000 });
    const mobileDimensions = await mobileStorefront.evaluate(element => ({ visible: element.getBoundingClientRect().width, container: element.closest(".admin-preview-fit").clientWidth }));
    assert.ok(mobileDimensions.visible <= mobileDimensions.container + 1, "mobile storefront preview fits a narrow screen");
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.getByRole("button", { name: "Homepage sections", exact: true }).click();
    await page.waitForURL("**/admin?tab=homepage");
    await page.getByRole("heading", { name: "Homepage editor" }).waitFor();
    await page.getByRole("button", { name: "Hero", exact: true }).click();
    await page.getByLabel("Hero headline, first line").fill("Keep this unsaved edit");
    revision = crypto.randomUUID();
    await page.getByRole("button", { name: "Save draft" }).click();
    await page.locator('.admin-homepage-sections [role="alert"]').waitFor();
    assert.match(await page.locator('.admin-homepage-sections [role="alert"]').innerText(), /saved draft changed in another session/i);
    await page.getByRole("button", { name: "Download my changes" }).waitFor();
    await page.getByRole("button", { name: "Reload saved draft" }).waitFor();
    assert.equal(await page.getByLabel("Hero headline, first line").inputValue(), "Keep this unsaved edit");
    assert.deepEqual(pageErrors, []);
    console.log(`PASS ${name}: edit, live preview, upload, reorder, publish, restore, viewport sizes`);
  } finally {
    await context.request.post(`${base}/api/admin/logout`).catch(() => {});
    await browser.close();
  }
}
