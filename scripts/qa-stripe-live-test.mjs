import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";
import ts from "typescript";
import { createRequire } from "node:module";
import { NextResponse } from "next/server.js";
const require = createRequire(import.meta.url);
let allowed = false, paymentStatus = "unpaid", refundCount = 0, savedRefund = null;
const session = () => ({ id: "cs_live_Test123", livemode: true, url: "https://checkout.stripe.com/c/pay/test", metadata: { purpose: "kcp-admin-one-dollar-test" }, currency: "usd", amount_total: 100, payment_status: paymentStatus, payment_intent: "pi_Test123" });
const stripe = { checkout: { sessions: { create: async input => { assert.equal(input.line_items[0].price_data.unit_amount, 100); return session(); }, retrieve: async () => session() } }, refunds: { list: async () => ({ data: savedRefund ? [savedRefund] : [] }), create: async (input, options) => { assert.equal(input.amount, 100); assert.match(options.idempotencyKey, /^test-refund-/); refundCount++; return savedRefund = { status: "pending" }; } } };
const source = await readFile("app/api/admin/stripe-test/route.ts", "utf8");
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exports = {};
const deps = { "next/server": { NextResponse }, "../_guard": { requireAdmin: async () => allowed ? null : NextResponse.json({}, { status: 401 }) }, "@/lib/stripe": { stripeClient: async () => stripe, siteUrl: () => "https://kingdomcustomprint.com" } };
vm.runInNewContext(code, { exports, require: name => deps[name] ?? require(name), URL, console });
const request = (body, cookie = "") => new Request("https://kingdomcustomprint.com/api/admin/stripe-test", { method: "POST", headers: { "Content-Type": "application/json", cookie }, body: JSON.stringify(body) });
assert.equal((await exports.POST(request({ action: "start" }))).status, 401);
allowed = true;
const start = await exports.POST(request({ action: "start" }));
assert.equal(start.status, 200);
assert.match(start.headers.get("set-cookie"), /HttpOnly/i);
assert.equal((await exports.POST(request({ action: "refund", session: "cs_live_Other" }, "kcp_stripe_test=cs_live_Test123"))).status, 400);
assert.equal((await exports.POST(request({ action: "refund", session: "cs_live_Test123" }, "kcp_stripe_test=cs_live_Test123"))).status, 409);
paymentStatus = "paid";
const refund = await exports.POST(request({ action: "refund", session: "cs_live_Test123" }, "kcp_stripe_test=cs_live_Test123"));
assert.equal((await refund.json()).refundStatus, "pending");
const retry = await exports.POST(request({ action: "refund", session: "cs_live_Test123" }, "kcp_stripe_test=cs_live_Test123"));
assert.equal((await retry.json()).refundStatus, "pending");
assert.equal(refundCount, 1);
console.log("PASS admin-only Stripe test checks $1 and paid status, then prevents duplicate refunds");
